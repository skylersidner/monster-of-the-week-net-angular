// Third bespoke-ruleset extraction pass, requested by the coordinator once
// Yoshi confirmed bespoke-ruleset-catalogue.md is real source-of-truth
// content, not just a structural reference — every entry needs its actual
// formatting captured, not left plain/tagless.
//
// The Divine's "Mission" ruleset: flat, description-only, pick 1 (see
// bespoke-ruleset-catalogue.md). Same shape as Crooked's Heat — plain text
// options, spliced against pdf.js-detected runs — so reuses
// extract-runs.mjs + splice-formatting.mjs exactly as build-crooked-review.mjs
// does, no new extraction technique needed.
//
// Page 15, Mission is the right-hand column, SHARING its x-range with the
// Divine's Moves section directly above it on the same page — verified
// this doesn't cause false positives (Moves' bold move-names/trigger
// phrases are long, specific strings that don't collide with Mission's
// unrelated option text) but flagged here since it's a slightly different
// situation than Crooked/Covenant's cleanly-separated columns.
//
// Usage: node build-divine-mission-review.mjs <pdfPath>

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pdfPath = process.argv[2];
if (!pdfPath) {
  console.error("Usage: node build-divine-mission-review.mjs <pdfPath>");
  process.exit(1);
}

const PAGE = 15;
const MIN_X = 525;
const MAX_X = 760;

// Plain text taken verbatim from bespoke-ruleset-catalogue.md's Divine ///
// Mission entries (already vetted against the PDF by the architecture
// pass) — this script's job is the formatting splice, not re-deriving text.
const mission = [
  "You are here to fight the schemes of an Adversary.",
  "The End of Days approaches. Your role is to guide these hunters and prevent it from coming to pass.",
  "The End of Days approaches. Your role is to guide these hunters and ensure it comes to pass.",
  "You have been exiled. You must work for the cause of Good without drawing attention from your brothers and sisters, as they are bound to execute you for your crimes.",
  "One of the other hunters has a crucial role to play in events to come. You must prepare them for their role, and protect them at any cost.",
];

const scratchDir = fs.mkdtempSync(path.join(process.env.TEMP || "/tmp", "hp-pdf-"));

const runsOut = execFileSync(
  process.execPath,
  [path.join(__dirname, "extract-runs.mjs"), pdfPath, String(PAGE), String(PAGE), "--json", "--minX", String(MIN_X), "--maxX", String(MAX_X)],
  { encoding: "utf8" }
);
const runsPath = path.join(scratchDir, "runs.json");
fs.writeFileSync(runsPath, runsOut);

function splice(text) {
  const textPath = path.join(scratchDir, `block-${Math.random().toString(36).slice(2)}.txt`);
  fs.writeFileSync(textPath, text, "utf8");
  const result = execFileSync(
    process.execPath,
    [path.join(__dirname, "splice-formatting.mjs"), textPath, runsPath, "--pages", String(PAGE)],
    { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] } // expected cross-section warnings suppressed, see build-crooked-review.mjs
  );
  return result.trim();
}

const options = mission.map((desc) => ({ title: null, descriptionText: splice(desc) }));

const output = {
  playbook: "The Divine",
  sections: [{ title: "Mission", options }],
};

const jsonPath = path.join(__dirname, "divine-mission-review.json");
fs.writeFileSync(jsonPath, JSON.stringify(output, null, 2));

function escapeForDisplay(html) {
  return html
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/&lt;(\/?)(b|i|ul|li)&gt;/g, "<$1$2>");
}

const items = options
  .map((opt) => `<li><div class="opt-desc">${escapeForDisplay(opt.descriptionText)}</div></li>`)
  .join("\n");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>The Divine — Mission — extraction review</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; line-height: 1.5; }
  h1 { font-size: 1.4rem; }
  h2 { margin-top: 2rem; border-bottom: 1px solid #ccc; }
  .options { list-style: none; padding: 0; }
  .options > li { margin-bottom: 1rem; padding: 0.75rem 1rem; background: #f7f7f7; border-radius: 6px; }
  .opt-desc b { color: #a33; }
  .opt-desc i { color: #369; }
  .note { color: #666; font-size: 0.9rem; }
</style>
</head>
<body>
<h1>The Divine — Mission — extraction review (page 15)</h1>
<p class="note">Generated by tools/pdf-extract/build-divine-mission-review.mjs. Flat, description-only, pick-1 ruleset (bespoke-ruleset-catalogue.md). Only one of the 5 options has any inline formatting in the source: option 5 italicizes "any" in "...protect them at <i>any</i> cost." — everything else is correctly plain text, confirmed from the raw PDF, not a gap in extraction. Italic rendered blue purely to make it easy to eyeball against the source PDF.</p>
<h2>Mission</h2>
<ul class="options">
${items}
</ul>
</body>
</html>
`;

const htmlPath = path.join(__dirname, "divine-mission-review.html");
fs.writeFileSync(htmlPath, html);

console.log(`Wrote ${jsonPath}`);
console.log(`Wrote ${htmlPath}`);

const hasItalic = options.some((o) => o.descriptionText.includes("<i>"));
console.log("\n<i> present: " + hasItalic + " (expected: true, exactly 1 of 5 options)");
