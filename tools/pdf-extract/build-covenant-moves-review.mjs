// Second validation pass, requested by the coordinator after Crooked's
// Background review was approved: The Covenant playbook's Moves section
// (page 9, middle column) exercises <ul>/<li> (nested roll-result
// breakdowns) and <i> (inline italic emphasis) — tag types Crooked's
// Background test didn't cover (that one was bold-only).
//
// Unlike build-crooked-review.mjs (which spliced pdf.js-detected bold runs
// into hand-copied plain text from bespoke-ruleset-catalogue.md), this
// script reconstructs full HTML directly from the PDF item stream via
// extract-moves.mjs, because the nested-list shape here can't be
// represented by simple inline-tag splicing into a flat paragraph — see
// extract-moves.mjs's own comments for why.
//
// Usage: node build-covenant-moves-review.mjs <pdfPath>

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pdfPath = process.argv[2];
if (!pdfPath) {
  console.error("Usage: node build-covenant-moves-review.mjs <pdfPath>");
  process.exit(1);
}

// Page 9, Moves column x-range — read off dump-page.mjs/list-fonts.mjs the
// same way Crooked's Background column range was found (see
// docs/hunter-playbooks/pdf-extraction-pipeline.md).
const PAGE = 9;
const MIN_X = 283;
const MAX_X = 520;

const out = execFileSync(
  process.execPath,
  [path.join(__dirname, "extract-moves.mjs"), pdfPath, String(PAGE), "--minX", String(MIN_X), "--maxX", String(MAX_X), "--json"],
  { encoding: "utf8" }
);
const extracted = JSON.parse(out);

const output = {
  playbook: "The Covenant",
  section: "Moves",
  intro: extracted.intro,
  moves: extracted.moves,
};

const jsonPath = path.join(__dirname, "covenant-moves-review.json");
fs.writeFileSync(jsonPath, JSON.stringify(output, null, 2));

function escapeForDisplay(html) {
  // Same technique as build-crooked-review.mjs: escape everything, then
  // un-escape just the enumerated tag subset so it actually renders.
  return html
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/&lt;(\/?)(b|i|ul|li)&gt;/g, "<$1$2>");
}

const items = output.moves
  .map((m) => `<li><div class="opt-title">${escapeForDisplay(m.title)}</div><div class="opt-desc">${escapeForDisplay(m.descriptionHtml)}</div></li>`)
  .join("\n");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>The Covenant — Moves — extraction review</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; line-height: 1.5; }
  h1 { font-size: 1.4rem; }
  h2 { margin-top: 2rem; border-bottom: 1px solid #ccc; }
  .options { list-style: none; padding: 0; }
  .options > li { margin-bottom: 1rem; padding: 0.75rem 1rem; background: #f7f7f7; border-radius: 6px; }
  .opt-title { font-weight: 700; margin-bottom: 0.25rem; }
  .opt-desc b { color: #a33; }
  .opt-desc i { color: #369; }
  .opt-desc ul { margin: 0.4rem 0 0.2rem 1.25rem; }
  .opt-desc ul li { list-style: disc; margin-bottom: 0.15rem; }
  .note { color: #666; font-size: 0.9rem; }
  .intro { color: #444; font-style: italic; margin-bottom: 1rem; }
</style>
</head>
<body>
<h1>The Covenant — Moves — extraction review (page 9)</h1>
<p class="note">Generated by tools/pdf-extract/build-covenant-moves-review.mjs. Validates &lt;ul&gt;/&lt;li&gt; (nested roll-result breakdowns) and &lt;i&gt; (inline italic emphasis) — tag types the earlier Crooked/Background review didn't exercise (that one was bold-only). Bold rendered red, italic blue, purely to make them easy to eyeball against the source PDF — the app itself will style &lt;b&gt;/&lt;i&gt;/&lt;ul&gt;/&lt;li&gt; normally.</p>
<p class="intro">${escapeForDisplay(output.intro)}</p>
<h2>Moves</h2>
<ul class="options">
${items}
</ul>
<p class="note">Known cosmetic artifact, not a bug in the extraction technique: "The Geek in the Chair" shows "pre- venting" — a real soft-hyphen line-break in the source PDF (the word "preventing" wraps across two lines). <code>pdftotext -layout</code> has this exact same limitation on hyphenated line-wraps; a human/agent authoring pass fixes it during review, same as any other line-wrap artifact already handled that way in this project's workflow.</p>
</body>
</html>
`;

const htmlPath = path.join(__dirname, "covenant-moves-review.html");
fs.writeFileSync(htmlPath, html);

console.log(`Wrote ${jsonPath}`);
console.log(`Wrote ${htmlPath}`);

// Validation checks, printed for visibility.
const hasUl = output.moves.some((m) => m.descriptionHtml.includes("<ul>") && m.descriptionHtml.includes("<li>"));
const hasItalic = output.moves.some((m) => m.descriptionHtml.includes("<i>"));
const hasBold = output.moves.some((m) => m.descriptionHtml.includes("<b>"));
console.log("\nValidation:");
console.log("  <ul>/<li> present: " + hasUl);
console.log("  <i> present:       " + hasItalic);
console.log("  <b> present:       " + hasBold);
