// Fourth playbook run through the pipeline, requested by the coordinator
// on Yoshi's behalf (Yoshi modeled Area of Study's structure, needed real
// formatting extraction to finalize it).
//
// The Action Scientist's "Area of Study" ruleset: page 1, middle of the
// front page's 3-column layout (x ~280-525, immediately left of "Moves").
// 7 options, 3 of which (Physics and Cosmology, Neurology and Psychology,
// Computers and Electronics) have an embedded bulleted sub-list — same
// shape extract-moves.mjs was built for on Covenant's Moves, so reused
// directly rather than the flat splice-formatting.mjs path.
//
// Checked all 7 options directly from the PDF rather than assuming from
// the coordinator's shape summary — a good thing, since 3 of the 4
// options flagged as "plain mechanical grant" actually have inline
// italic/bold the summary didn't anticipate (see the script's own
// console output and docs/hunter-playbooks/pdf-extraction-pipeline.md
// for the full trace). Only "Space" turned out to be genuinely plain.
//
// Usage: node build-action-scientist-area-of-study-review.mjs <pdfPath>

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const pdfPath = process.argv[2];
if (!pdfPath) {
  console.error("Usage: node build-action-scientist-area-of-study-review.mjs <pdfPath>");
  process.exit(1);
}

const PAGE = 1;
const MIN_X = 280;
const MAX_X = 525;

const out = execFileSync(
  process.execPath,
  [path.join(__dirname, "extract-moves.mjs"), pdfPath, String(PAGE), "--minX", String(MIN_X), "--maxX", String(MAX_X), "--json"],
  { encoding: "utf8" }
);
const extracted = JSON.parse(out);

const output = {
  playbook: "The Action Scientist",
  section: "Area of Study",
  intro: extracted.intro,
  options: extracted.moves, // same {title, descriptionHtml} shape as Covenant's "moves" — Area of Study is a BespokeSection, not a Moves list, so named "options" here to match that schema's vocabulary
};

const jsonPath = path.join(__dirname, "action-scientist-area-of-study-review.json");
fs.writeFileSync(jsonPath, JSON.stringify(output, null, 2));

function escapeForDisplay(html) {
  return html
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/&lt;(\/?)(b|i|ul|li)&gt;/g, "<$1$2>");
}

const items = output.options
  .map((o) => `<li><div class="opt-title">${escapeForDisplay(o.title)}</div><div class="opt-desc">${escapeForDisplay(o.descriptionHtml)}</div></li>`)
  .join("\n");

const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>The Action Scientist — Area of Study — extraction review</title>
<style>
  body { font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; line-height: 1.5; }
  h1 { font-size: 1.4rem; }
  h2 { margin-top: 2rem; border-bottom: 1px solid #ccc; }
  .options { list-style: none; padding: 0; }
  .options > li { margin-bottom: 1rem; padding: 0.75rem 1rem; background: #f7f7f7; border-radius: 6px; }
  .opt-title { font-weight: 700; margin-bottom: 0.25rem; }
  .opt-desc b { color: #a33; }
  .opt-desc i { color: #369; }
  .opt-desc ul { margin: 0.4rem 0 0.2rem 1.25rem; }
  .opt-desc ul li { list-style: disc; margin-bottom: 0.15rem; }
  .note { color: #666; font-size: 0.9rem; }
  .intro { color: #444; font-style: italic; margin-bottom: 1rem; }
</style>
</head>
<body>
<h1>The Action Scientist — Area of Study — extraction review (page 1)</h1>
<p class="note">Generated by tools/pdf-extract/build-action-scientist-area-of-study-review.mjs. All 7 options checked directly against the PDF, not assumed from shape. Findings: <b>Physics and Cosmology</b> has both a bold inline phrase ("investigate a mystery") AND its expected 3-item bulleted list; <b>Biology and Chemistry</b>, <b>Violence</b>, and <b>Mechanics and Engineering</b> were expected to be plain but each has real inline emphasis (italic, italic, and two italic spans respectively; Violence also has bold); <b>Neurology and Psychology</b> and <b>Computers and Electronics</b> have both inline italic AND their expected roll-result breakdown lists; only <b>Space</b> is genuinely plain, confirmed from the raw PDF. Bold rendered red, italic blue, purely to make them easy to eyeball against the source.</p>
<p class="intro">${escapeForDisplay(output.intro)}</p>
<h2>Area of Study</h2>
<ul class="options">
${items}
</ul>
</body>
</html>
`;

const htmlPath = path.join(__dirname, "action-scientist-area-of-study-review.html");
fs.writeFileSync(htmlPath, html);

console.log(`Wrote ${jsonPath}`);
console.log(`Wrote ${htmlPath}`);

console.log("\nPer-option formatting found:");
for (const o of output.options) {
  const hasB = o.descriptionHtml.includes("<b>");
  const hasI = o.descriptionHtml.includes("<i>");
  const hasList = o.descriptionHtml.includes("<ul>");
  console.log(`  ${o.title}: bold=${hasB} italic=${hasI} list=${hasList}`);
}
